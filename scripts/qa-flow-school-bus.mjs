import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
const {chromium}=await import(process.env.FLOW_PLAYWRIGHT?pathToFileURL(process.env.FLOW_PLAYWRIGHT).href:'playwright');
const live=process.argv.includes('--live');
const root=new URL('../',import.meta.url);
const out=resolve(process.env.FLOW_QA_DIR||'qa-flow-browser-output',live?'school-bus-live':'school-bus-candidate');
mkdirSync(out,{recursive:true});
const origin='https://blank-app.agfvrd.workers.dev';
const names=['index.html','flow-icons-handdrawn-v1.js','flow-bus-nearby-v2.js','flow-bus-nearby-v1.css','flow-onboarding-v2.js','flow-ux-quick-actions-v1.js','flow-ux-compact-v2.css','flow-school-shortcuts-v1.js','flow-school-shortcuts-v1.css'];
const files=new Map(names.map(n=>[n,readFileSync(new URL(n,root))]));
const browser=await chromium.launch({headless:true,executablePath:process.env.FLOW_CHROME||undefined,args:['--no-sandbox']});
const results=[];
async function run(w,theme){
 const c=await browser.newContext({viewport:{width:w,height:w<871?844:900},isMobile:w<871,hasTouch:w<871});
 const p=await c.newPage(),o={w,theme,checks:[],errors:[],assetErrors:[]};
 const check=(name,condition)=>{assert.ok(condition,name);o.checks.push(name)};
 p.on('pageerror',e=>o.errors.push(e.message));
 p.on('response',r=>{if(r.url().includes('/flow-v2/frontend-rust/dist/')&&r.status()>=400)o.assetErrors.push(r.url())});
 if(!live)await p.route(origin+'/**',r=>{
   const u=new URL(r.request().url()),n=u.pathname==='/'?'index.html':u.pathname.split('/').pop();
   if(!files.has(n))return r.continue();
   return r.fulfill({status:200,contentType:n.endsWith('.html')?'text/html; charset=utf-8':n.endsWith('.css')?'text/css; charset=utf-8':'application/javascript; charset=utf-8',body:files.get(n)});
 });
 const nav=w<871?'.mobile-bottom':'.rail-navigation';
 const tab=async name=>{await p.locator(nav+'>button').filter({hasText:name}).first().click();await p.waitForTimeout(280)};
 const screen=async name=>{check(name+' no overflow',await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));if(w===390||w===1366)await p.screenshot({path:resolve(out,w+'-'+theme+'-'+name+'.png')});};
 try{
   await p.goto(origin+'/?school-bus-qa=1',{waitUntil:'domcontentloaded'});
   await p.waitForSelector('#school-search');
   await p.evaluate(()=>localStorage.setItem('flow-school-guide-v1','done'));
   const input=p.locator('#school-search'),list=p.locator('.school-search-results');
   await input.fill('정동고');
   await p.waitForSelector('.search-option',{timeout:20000});
   await input.press('ArrowDown');
   check('keyboard reaches real result',await p.evaluate(()=>document.activeElement?.classList.contains('search-option')));
   await p.keyboard.press('Enter');
   const change=p.getByRole('button',{name:'선택한 학교 변경'});
   await change.waitFor();await p.waitForTimeout(150);
   check('results hidden after selection',!(await list.isVisible()));
   check('focus grade after selection',await p.locator('.two-fields select').evaluate(e=>e===document.activeElement));
   await screen('school-selected');
   await change.click();check('change focuses search',await input.evaluate(e=>e===document.activeElement));
   await input.fill('정동초등학교');
   await p.waitForFunction(()=>[...document.querySelectorAll('.search-option strong')].some(x=>x.textContent.includes('정동초등학교')),null,{timeout:25000});
   await p.locator('.search-option').filter({hasText:'정동초등학교'}).first().click();
   await p.waitForFunction(()=>document.querySelector('.two-fields select')?.options.length===6);
   check('elementary six grades',true);
   await change.click();await input.fill('정동고');
   await p.waitForFunction(()=>[...document.querySelectorAll('.search-option strong')].some(x=>x.textContent==='정동고등학교'),null,{timeout:25000});
   await p.locator('.search-option').filter({hasText:'정동고등학교'}).first().click();
   await p.waitForFunction(()=>document.querySelector('.two-fields select')?.options.length===3);
   await p.locator('.two-fields select').selectOption('2');await p.locator('.two-fields input').fill('6');
   await p.locator('.setup-complete').click();
   await p.waitForSelector('.flow-shell',{timeout:25000});
   if(theme==='dark'){await tab('설정');await p.locator('.setting-toggle').filter({hasText:'라이트 모드'}).click();await p.waitForFunction(()=>document.documentElement.dataset.theme==='dark');}
   await tab('학교');await p.waitForSelector('.flow-school-change');await screen('school');
   await p.locator('.flow-school-change').click();await p.waitForSelector('.settings-sheet');
   check('school change goes to native settings',await p.locator('.setting-toggle').filter({hasText:'다시 선택'}).isVisible());
   await tab('버스');await p.waitForSelector('.flow-favorites');
   check('empty explicit favorites',await p.locator('.flow-favorite-empty').isVisible());
   const search=p.locator('#bus-stop-query');
   await search.fill('동대구역');await p.locator('.bus-search button').click();
   await p.waitForSelector('.bus-stop-option',{timeout:25000});
   const first=p.locator('.bus-stop-option').filter({hasText:'정류장 09060'}).first();
   await first.click();
   const star=p.locator('.bus-selected .flow-favorite-toggle');
   await star.waitFor({timeout:15000});
   check('last stop not implicitly favorite',(await star.getAttribute('aria-pressed'))==='false');
   await star.click();
   await p.waitForSelector('.flow-favorite-row');
   check('saved state explicit',(await star.getAttribute('aria-pressed'))==='true');
   check('favorite correct number',(await p.locator('.flow-favorite-row').innerText()).includes('09060'));
   await screen('bus-saved');
   await search.fill('동대구역');await p.locator('.bus-search button').click();
   await p.waitForSelector('.bus-stop-option',{timeout:25000});
   await p.locator('.bus-stop-option').filter({hasText:'정류장 09061'}).first().click();
   await p.waitForFunction(()=>document.querySelector('.bus-selected .bus-stop-name span')?.textContent.includes('09061'));
   await p.waitForFunction(()=>document.querySelector('.bus-selected .flow-favorite-toggle')?.getAttribute('aria-pressed')==='false');
   await star.click();await p.waitForFunction(()=>document.querySelectorAll('.flow-favorite-row').length===2);
   check('two distinct stop directions saved',true);
   await p.reload({waitUntil:'domcontentloaded'});await p.waitForSelector('.flow-shell');
   await tab('버스');await p.waitForFunction(()=>document.querySelectorAll('.flow-favorite-row').length===2);
   check('favorites survive reload',true);
   await p.locator('.flow-favorite-open').filter({hasText:'09060'}).click();
   await p.waitForFunction(()=>document.querySelector('.bus-selected .bus-stop-name span')?.textContent.includes('09060'),null,{timeout:25000});
   check('favorite opens exact stop direction',true);
   const remove=p.locator('.flow-favorite-row').filter({hasText:'09060'}).locator('.flow-favorite-toggle');
   await remove.click();await p.waitForFunction(()=>document.querySelectorAll('.flow-favorite-row').length===1);
   check('remove only chosen favorite',!(await p.locator('.flow-favorite-list').innerText()).includes('09060'));
   await p.locator('.flow-favorite-row .flow-favorite-toggle').click();
   await p.waitForSelector('.flow-favorite-empty');
   check('remove last favorite',true);
   check('native last stop preserved',await p.evaluate(()=>JSON.parse(localStorage.getItem('flow-daegu-favorite-stop-v1')).number==='09060'));
   check('no JS errors',o.errors.length===0);check('no static HTTP errors',o.assetErrors.length===0);
   o.pass=true;
 }catch(e){o.pass=false;o.error=String(e);try{await p.screenshot({path:resolve(out,w+'-'+theme+'-failure.png')})}catch{}}
 finally{await c.close();}
 console.log(JSON.stringify(o));return o;
}
try{results.push(...await Promise.all([[320,'light'],[390,'dark'],[1366,'light']].map(([w,t])=>run(w,t))));}finally{await browser.close()}
writeFileSync(resolve(out,'result.json'),JSON.stringify(results,null,2));
if(results.some(r=>!r.pass))process.exitCode=1;
